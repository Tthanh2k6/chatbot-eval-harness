import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { fileURLToPath } from 'node:url';
import { createServer } from '../src/server.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT_DIR = path.resolve(__dirname, '..');
const RESULTS_PATH = path.join(ROOT_DIR, 'results.json');
const MIN_PASS_RATE = 0.95;

async function main() {
  const port = Number(process.env.PORT) || 3917;
  const server = createServer();

  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(port, () => resolve());
  });

  console.log(`Started Quillnote server on http://localhost:${port} for evaluation...`);

  let exitCode = 0;
  try {
    if (fs.existsSync(RESULTS_PATH)) {
      fs.unlinkSync(RESULTS_PATH);
    }

    const cmd = 'npx promptfoo eval -c evals/promptfooconfig.yaml --no-cache -o results.json';
    console.log(`Running: ${cmd}`);
    // Must be async: spawnSync would block this process's event loop, so the
    // in-process server could not answer promptfoo's requests (deadlock).
    const child = spawn(cmd, {
      cwd: ROOT_DIR,
      stdio: 'inherit',
      shell: true,
      env: { ...process.env },
    });
    await once(child, 'exit');

    if (!fs.existsSync(RESULTS_PATH)) {
      console.error('Error: results.json was not generated by promptfoo.');
      exitCode = 1;
      return;
    }

    const raw = JSON.parse(fs.readFileSync(RESULTS_PATH, 'utf8'));
    const resultsContainer = raw.results || raw;
    const items = Array.isArray(resultsContainer)
      ? resultsContainer
      : Array.isArray(resultsContainer.results)
        ? resultsContainer.results
        : [];

    let passed = 0;
    let total = items.length;

    if (total > 0) {
      passed = items.filter((item) => item && item.success === true).length;
    } else if (
      resultsContainer.stats &&
      typeof resultsContainer.stats.successes === 'number'
    ) {
      passed = resultsContainer.stats.successes;
      total =
        passed +
        (resultsContainer.stats.failures || 0) +
        (resultsContainer.stats.errors || 0);
    }

    const passRate = total > 0 ? passed / total : 0;
    const pct = (passRate * 100).toFixed(1);
    console.log(
      `\nQuality Gate Summary: ${passed}/${total} tests passed (${pct}%). Required threshold: 95.0%.`
    );

    if (total === 0 || passRate < MIN_PASS_RATE) {
      console.error(`Quality gate FAILED: pass rate ${pct}% is below 95.0%.`);
      exitCode = 1;
    } else {
      console.log(`Quality gate PASSED: pass rate ${pct}% meets >= 95.0% threshold.`);
      exitCode = 0;
    }
  } finally {
    server.closeAllConnections?.();
    await new Promise((resolve) => server.close(resolve));
  }

  process.exit(exitCode);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
